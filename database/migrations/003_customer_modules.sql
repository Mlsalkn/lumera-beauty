CREATE TABLE IF NOT EXISTS favorites (
 customer_id BIGINT UNSIGNED NOT NULL,
 service_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(customer_id,service_id),
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS customer_preferences (
 customer_id BIGINT UNSIGNED PRIMARY KEY,
 appointment_notifications BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL,
 appointment_id BIGINT UNSIGNED NULL,
 event VARCHAR(30) NOT NULL,
 message VARCHAR(500) NOT NULL,
 read_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX customer_notifications(customer_id,read_at,id),
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS appointment_status_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 appointment_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NULL,
 event VARCHAR(30) NOT NULL,
 old_status VARCHAR(12) NULL,
 new_status VARCHAR(12) NOT NULL,
 old_start_at DATETIME NULL,
 new_start_at DATETIME NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX appointment_history(appointment_id,id),
 FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT,
 FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS email_change_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL UNIQUE,
 old_email VARCHAR(190) NOT NULL,
 new_email VARCHAR(190) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL,
 created_at DATETIME NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
